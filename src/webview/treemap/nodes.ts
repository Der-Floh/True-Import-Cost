import type { TreemapKindDto, TreemapNodeDto } from '../../shared/dashboard';

export type TileAction = 'drill' | 'open' | 'explain' | 'none';

export type TileFamily = 'project' | 'package' | 'generated' | 'other';

export interface GroupLimits {
    readonly minimumShare: number;
    readonly maxTiles: number;
}

const KIND_TEXT: Readonly<Record<TreemapKindDto, string>> = {
    root: 'build',
    package: 'package',
    project: 'project code',
    generated: 'generated by the bundler',
    module: 'module',
    other: 'other',
};

const groups = new WeakSet<TreemapNodeDto>();

export function measuredChildren(node: TreemapNodeDto): TreemapNodeDto[] {
    return (node.children ?? []).filter(child => Number.isFinite(child.bytes) && child.bytes > 0);
}

export function hasContents(node: TreemapNodeDto): boolean {
    return measuredChildren(node).length > 0;
}

export function isSmallerGroup(node: TreemapNodeDto): boolean {
    return groups.has(node);
}

function smallerGroup(parent: TreemapNodeDto, members: readonly TreemapNodeDto[]): TreemapNodeDto {
    const group: TreemapNodeDto = {
        id: `${parent.id}#smaller`,
        label: `${members.length} smaller items`,
        bytes: members.reduce((sum, member) => sum + member.bytes, 0),
        kind: 'other',
        lazy: members.every(member => member.lazy),
        children: members,
    };
    groups.add(group);
    return group;
}

export function visibleChildren(node: TreemapNodeDto, limits: GroupLimits): TreemapNodeDto[] {
    const children = measuredChildren(node).sort((a, b) => b.bytes - a.bytes);
    const maxTiles = Math.max(2, Math.floor(limits.maxTiles));
    const total = children.reduce((sum, child) => sum + child.bytes, 0);
    const threshold = total * limits.minimumShare;
    const large = children.filter(child => child.bytes >= threshold).length;
    const limit = children.length > maxTiles ? maxTiles - 1 : children.length;
    const kept = large === 0 ? limit : Math.min(large, limit);
    if (children.length - kept < 2) {
        return children;
    }
    return [...children.slice(0, kept), smallerGroup(node, children.slice(kept))];
}

function regroup(parent: TreemapNodeDto, previous: TreemapNodeDto): TreemapNodeDto | undefined {
    const ids = new Set((previous.children ?? []).map(child => child.id));
    const members = measuredChildren(parent)
        .filter(child => ids.has(child.id))
        .sort((a, b) => b.bytes - a.bytes);
    return members.length < 2 ? undefined : smallerGroup(parent, members);
}

export function rebase(root: TreemapNodeDto, path: readonly TreemapNodeDto[]): TreemapNodeDto[] {
    const rebased: TreemapNodeDto[] = [];
    let parent = root;
    for (const step of path) {
        const next = isSmallerGroup(step)
            ? regroup(parent, step)
            : measuredChildren(parent).find(child => child.id === step.id);
        if (next === undefined || !hasContents(next)) {
            break;
        }
        rebased.push(next);
        parent = next;
    }
    return rebased;
}

export function tileAction(node: TreemapNodeDto): TileAction {
    if (hasContents(node)) {
        return 'drill';
    }
    if (node.kind === 'module' && node.openable === true && node.moduleId !== undefined) {
        return 'open';
    }
    if (node.kind === 'package' && node.packageName !== undefined) {
        return 'explain';
    }
    return 'none';
}

export function kindText(kind: TreemapKindDto): string {
    return KIND_TEXT[kind];
}

export function familyOf(kind: TreemapKindDto): TileFamily | undefined {
    return kind === 'project' || kind === 'package' || kind === 'generated' || kind === 'other' ? kind : undefined;
}

export function tileFamily(node: TreemapNodeDto, trail: readonly TreemapNodeDto[]): TileFamily {
    const own = familyOf(node.kind);
    if (own !== undefined) {
        return own;
    }
    for (let index = trail.length - 1; index >= 0; index--) {
        const ancestor = trail[index];
        const family = ancestor === undefined || isSmallerGroup(ancestor) ? undefined : familyOf(ancestor.kind);
        if (family !== undefined && family !== 'other') {
            return family;
        }
    }
    return 'other';
}
