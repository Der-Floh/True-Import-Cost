import { flushPromises } from '@vue/test-utils';
import { afterEach, describe, expect, it, vi } from 'vitest';

import { buttonByText, deliver, mountDashboard, section, takeMessages, textsOf } from './support/dashboard';
import { dashboardModel, defaultTreemap, groupNode, moduleNode, packageNode, rootNode, TARGET_KEY } from './support/model';

import type { Dashboard } from './support/dashboard';
import type { TreemapNodeDto } from '../../shared/dashboard';

function mapOf(wrapper: Dashboard) {
    return section(wrapper, 'treemap');
}

function tileIds(wrapper: Dashboard): string[] {
    return mapOf(wrapper).findAll('.tile__button').map(button => button.attributes('data-node') ?? '');
}

function tile(wrapper: Dashboard, id: string) {
    const button = mapOf(wrapper).findAll('.tile__button').find(candidate => candidate.attributes('data-node') === id);
    if (button === undefined) {
        throw new Error(`No tile for ${id}`);
    }
    return button;
}

function crumbs(wrapper: Dashboard): string[] {
    return textsOf(mapOf(wrapper), '.crumbs__item');
}

async function mapWith(root: TreemapNodeDto): Promise<Dashboard> {
    return mountDashboard(dashboardModel({ selected: { treemap: root } }));
}

afterEach(() => {
    vi.unstubAllGlobals();
});

describe('the bundle map', () => {
    it('shows one tile per group, largest first, each naming its size and share', async () => {
        const wrapper = await mountDashboard(dashboardModel());

        expect(tileIds(wrapper)).toEqual(['package:node_modules/vue', 'group:project', 'package:node_modules/lodash-es', 'group:generated']);
        const vue = tile(wrapper, 'package:node_modules/vue');
        expect(vue.attributes('title')).toBe('vue\n60 kB, 55% of webview\npackage\nSelect to see what is inside.');
        expect(vue.attributes('aria-label')).toBe('vue: 60 kB, 55% of webview, package. Select to see what is inside.');
        expect(vue.element.tagName).toBe('BUTTON');
        expect(vue.find('.tile__label').text()).toBe('vue');
        expect(vue.find('.tile__size').text()).toBe('60 kB');
    });

    it('shows where it is and how big that is', async () => {
        const wrapper = await mountDashboard(dashboardModel());

        expect(crumbs(wrapper)).toEqual(['webview']);
        expect(mapOf(wrapper).find('.crumbs__current').attributes('aria-current')).toBe('location');
        expect(mapOf(wrapper).find('.map-bar__size').text()).toBe('110 kB');
    });

    it('colours tiles by kind', async () => {
        const wrapper = await mountDashboard(dashboardModel());

        expect(tile(wrapper, 'group:project').element.parentElement?.classList.contains('tile--project')).toBe(true);
        expect(tile(wrapper, 'package:node_modules/vue').element.parentElement?.classList.contains('tile--package')).toBe(true);
        expect(tile(wrapper, 'group:generated').element.parentElement?.classList.contains('tile--generated')).toBe(true);
        expect(textsOf(mapOf(wrapper), '.legend__item')).toEqual(['Your code', 'Packages', 'Generated by the bundler']);
    });

    it('marks lazily loaded and duplicated tiles in words as well as on the tile', async () => {
        const wrapper = await mapWith(rootNode([
            packageNode('chart.js', [moduleNode('node_modules/chart.js/dist/chart.js', 50_000, { lazy: true })], { lazy: true }),
            packageNode('date-fns', [moduleNode('node_modules/date-fns/format.js', 20_000)], { label: 'date-fns 2.30.0', duplicate: true }),
        ]));

        const chart = tile(wrapper, 'package:node_modules/chart.js');
        const dates = tile(wrapper, 'package:node_modules/date-fns');
        expect(chart.element.parentElement?.classList.contains('tile--lazy')).toBe(true);
        expect(chart.attributes('aria-label')).toContain('package, loaded lazily.');
        expect(dates.element.parentElement?.classList.contains('tile--duplicate')).toBe(true);
        expect(dates.attributes('title')).toContain('bundled more than once');
        expect(textsOf(mapOf(wrapper), '.legend__item')).toEqual([
            'Packages',
            'Hatched: loaded lazily',
            'Corner mark: package bundled more than once',
        ]);
    });

    it('drills into a group, and back up with the breadcrumbs', async () => {
        const wrapper = await mountDashboard(dashboardModel());

        await tile(wrapper, 'group:project').trigger('click');
        expect(crumbs(wrapper)).toEqual(['webview', 'Project sources (src/)']);
        expect(tileIds(wrapper)).toEqual(['dir:src/components', 'module:src/main.ts']);

        await tile(wrapper, 'dir:src/components').trigger('click');
        expect(crumbs(wrapper)).toEqual(['webview', 'Project sources (src/)', 'components']);
        expect(tileIds(wrapper)).toEqual(['module:src/components/App.vue', 'module:src/components/Lazy.vue']);

        await buttonByText(mapOf(wrapper), 'Project sources (src/)').trigger('click');
        expect(crumbs(wrapper)).toEqual(['webview', 'Project sources (src/)']);

        await buttonByText(mapOf(wrapper), 'webview').trigger('click');
        expect(crumbs(wrapper)).toEqual(['webview']);
        expect(tileIds(wrapper)).toHaveLength(4);
    });

    it('colours the files inside a group like the group, and lists what is lazy', async () => {
        const wrapper = await mountDashboard(dashboardModel());

        await tile(wrapper, 'group:project').trigger('click');
        await tile(wrapper, 'dir:src/components').trigger('click');

        expect(tile(wrapper, 'module:src/components/App.vue').element.parentElement?.classList.contains('tile--project')).toBe(true);
        expect(textsOf(mapOf(wrapper), '.legend__item')).toEqual(['Your code', 'Hatched: loaded lazily']);
    });

    it('moves the focus into the group it opened, and back to it on the way up', async () => {
        const wrapper = await mountDashboard(dashboardModel());

        await tile(wrapper, 'group:project').trigger('click');
        await flushPromises();
        expect(document.activeElement).toBe(tile(wrapper, 'dir:src/components').element);
        expect(mapOf(wrapper).find('[aria-live="polite"]').text()).toBe('Project sources (src/): 45 kB in 2 tiles');

        await buttonByText(mapOf(wrapper), 'webview').trigger('click');
        await flushPromises();
        expect(document.activeElement).toBe(tile(wrapper, 'group:project').element);
    });

    it('opens a module the host can open', async () => {
        const wrapper = await mountDashboard(dashboardModel());

        await tile(wrapper, 'group:project').trigger('click');
        expect(tile(wrapper, 'module:src/main.ts').attributes('title')).toContain('Select to open the file.');
        await tile(wrapper, 'module:src/main.ts').trigger('click');

        expect(takeMessages()).toEqual([{ type: 'openModule', target: TARGET_KEY, moduleId: 'src/main.ts' }]);
    });

    it('does nothing for a module that cannot be opened', async () => {
        const wrapper = await mountDashboard(dashboardModel());

        await tile(wrapper, 'group:generated').trigger('click');
        const helper = tile(wrapper, 'module:\0vite/preload-helper.js');
        await helper.trigger('click');

        expect(helper.attributes('aria-disabled')).toBe('true');
        expect(takeMessages()).toEqual([]);
        expect(crumbs(wrapper)).toEqual(['webview', 'Generated by the bundler']);
    });

    it('offers to explain a package and show its importers from its tile', async () => {
        const wrapper = await mountDashboard(dashboardModel());

        await mapOf(wrapper).find('[aria-label="Explain why vue is included"]').trigger('click');
        await mapOf(wrapper).find('[aria-label="Show importers of vue"]').trigger('click');

        expect(takeMessages()).toEqual([
            { type: 'explain', target: TARGET_KEY, packageName: 'vue' },
            { type: 'showImporters', target: TARGET_KEY, packageName: 'vue' },
        ]);
    });

    it('offers the same for the package it shows', async () => {
        const wrapper = await mountDashboard(dashboardModel());
        expect(textsOf(mapOf(wrapper), '.map-bar__actions button')).toEqual([]);

        await tile(wrapper, 'package:node_modules/lodash-es').trigger('click');
        await buttonByText(mapOf(wrapper), 'Explain why included').trigger('click');
        await buttonByText(mapOf(wrapper), 'Show importers').trigger('click');

        expect(takeMessages()).toEqual([
            { type: 'explain', target: TARGET_KEY, packageName: 'lodash-es' },
            { type: 'showImporters', target: TARGET_KEY, packageName: 'lodash-es' },
        ]);
    });

    it('explains a package that has no modules to show', async () => {
        const wrapper = await mapWith(rootNode([packageNode('vue', [], { bytes: 60_000 })]));

        await tile(wrapper, 'package:node_modules/vue').trigger('click');

        expect(takeMessages()).toEqual([{ type: 'explain', target: TARGET_KEY, packageName: 'vue' }]);
    });

    it('folds tiles too small to see into a group of smaller items, which opens like any group', async () => {
        const tiny = Array.from({ length: 100 }, (_, index) => moduleNode(`src/tiny-${index}.ts`, 100));
        const wrapper = await mapWith(rootNode([moduleNode('src/big.ts', 1_000_000), ...tiny]));

        expect(tileIds(wrapper)).toEqual(['module:src/big.ts', 'root#smaller']);
        expect(tile(wrapper, 'root#smaller').attributes('aria-label')).toBe('100 smaller items: 10 kB, <1% of webview. Select to see what is inside.');
        await tile(wrapper, 'root#smaller').trigger('click');

        expect(crumbs(wrapper)).toEqual(['webview', '100 smaller items']);
        expect(tileIds(wrapper)).toHaveLength(60);
        expect(tile(wrapper, 'root#smaller#smaller').attributes('aria-label')).toMatch(/^41 smaller items: 4.1 kB, /);
    });

    it('hides the label of a tile too small for it, but keeps its tooltip', async () => {
        const wrapper = await mapWith(rootNode([moduleNode('src/big.ts', 100_000), moduleNode('src/small.ts', 300)]));

        const small = tile(wrapper, 'module:src/small.ts');
        expect(small.find('.tile__label').exists()).toBe(false);
        expect(small.attributes('title')).toBe('small.ts\n300 B, <1% of webview\nmodule\nSelect to open the file.');
    });

    it('keeps its place when the host sends a new model, as long as the group still exists', async () => {
        const wrapper = await mountDashboard(dashboardModel());
        await tile(wrapper, 'package:node_modules/vue').trigger('click');

        await deliver(dashboardModel({ selected: { treemap: rootNode([packageNode('vue', [moduleNode('node_modules/vue/index.js', 90_000)])]) } }));
        expect(crumbs(wrapper)).toEqual(['webview', 'vue']);
        expect(tileIds(wrapper)).toEqual(['module:node_modules/vue/index.js']);

        await deliver(dashboardModel({ selected: { treemap: rootNode([moduleNode('src/main.ts', 5_000)]) } }));
        expect(crumbs(wrapper)).toEqual(['webview']);
    });

    it('starts at the top again for another target', async () => {
        const wrapper = await mountDashboard(dashboardModel());
        await tile(wrapper, 'package:node_modules/vue').trigger('click');

        await deliver(dashboardModel({ selected: { key: 'file:///w/.true-import-cost/other.json', id: 'other', treemap: defaultTreemap() } }));

        expect(crumbs(wrapper)).toEqual(['webview']);
    });

    it('lays the tiles out for the width it measures', async () => {
        let resize: ResizeObserverCallback | undefined;
        vi.stubGlobal('ResizeObserver', class {
            public constructor(callback: ResizeObserverCallback) {
                resize = callback;
            }

            public observe(): void {}

            public disconnect(): void {}
        });
        const wrapper = await mountDashboard(dashboardModel());

        resize?.([{ contentRect: { width: 400 } } as ResizeObserverEntry], {} as ResizeObserver);
        await flushPromises();

        const map = mapOf(wrapper).find('.map');
        expect(map.attributes('style')).toContain('height: 312px');
        for (const element of mapOf(wrapper).findAll('.tile')) {
            const style = (element.element as HTMLElement).style;
            expect(Number.parseFloat(style.left) + Number.parseFloat(style.width)).toBeLessThanOrEqual(400.001);
            expect(Number.parseFloat(style.top) + Number.parseFloat(style.height)).toBeLessThanOrEqual(312.001);
        }
    });

    it('says so when the build records no module sizes', async () => {
        const wrapper = await mapWith(rootNode([]));

        expect(mapOf(wrapper).text()).toContain('The build metadata records no module sizes for this target.');
        expect(mapOf(wrapper).find('.map').exists()).toBe(false);
    });

    it('treats nested groups of the same kind as places to go', async () => {
        const nested = groupNode('dir:src', 'src', 'project', [groupNode('dir:src/a', 'a', 'project', [moduleNode('src/a/x.ts', 10)])]);
        const wrapper = await mapWith(rootNode([nested]));

        await tile(wrapper, 'dir:src').trigger('click');
        await tile(wrapper, 'dir:src/a').trigger('click');

        expect(crumbs(wrapper)).toEqual(['webview', 'src', 'a']);
        expect(tileIds(wrapper)).toEqual(['module:src/a/x.ts']);
    });
});
