export function targetSummary(target: TargetDashboardDto, overrides: Partial<TargetSummaryDto> = {}): TargetSummaryDto {
    return {
        key: target.key,
        id: target.id,
        bundler: target.bundler,
        ...(target.mode === undefined ? {} : { mode: target.mode }),
        createdAt: target.createdAt,
        totalBytes: target.totals.total,
        ...overrides,
    };
}

export function otherTargetSummary(overrides: Partial<TargetSummaryDto> = {}): TargetSummaryDto {
    return {
        key: OTHER_KEY,
        id: 'extension-host',
        bundler: 'esbuild 0.28.2',
        mode: 'production',
        createdAt: Date.now() - 2 * HOUR,
        totalBytes: 97_400,
        ...overrides,
    };
}

export interface ModelOptions {
    readonly selected?: Partial<TargetDashboardDto>;
    readonly targets?: (selected: TargetDashboardDto) => readonly TargetSummaryDto[];
    readonly comparison?: TargetComparisonDto;
    readonly historyEnabled?: boolean;
}

export function dashboardModel(options: ModelOptions = {}): DashboardModel {
    const selected = targetDashboard(options.selected);
    return {
        targets: options.targets?.(selected) ?? [targetSummary(selected)],
        selected,
        ...(options.comparison === undefined ? {} : { comparison: options.comparison }),
        historyEnabled: options.historyEnabled ?? true,
    };
}

export function modelWithoutTarget(targets: readonly TargetSummaryDto[] = []): DashboardModel {
    return { targets, historyEnabled: true };
}

