import type {
    AssetGroupDto,
    BudgetKindDto,
    BudgetStateDto,
    ChunkRowDto,
    DashboardModel,
    HistoryPointDto,
    ModuleChangeDto,
    PackageRowDto,
    SizeTotalsDto,
    TargetComparisonDto,
    TargetDashboardDto,
    TargetSummaryDto,
    TreemapKindDto,
    TreemapNodeDto,
} from '../../../shared/dashboard';

export const MINUTE = 60_000;
export const HOUR = 60 * MINUTE;
export const DAY = 24 * HOUR;

export const TARGET_KEY = 'file:///w/.true-import-cost/webview.json';
export const OTHER_KEY = 'file:///w/.true-import-cost/extension-host.json';

export function sizeTotals(overrides: Partial<SizeTotalsDto> = {}): SizeTotalsDto {
    return { total: 400_000, javascript: 300_000, css: 20_000, assets: 80_000, initial: 250_000, lazy: 70_000, ...overrides };
}

function sum(nodes: readonly TreemapNodeDto[]): number {
    return nodes.reduce((total, node) => total + node.bytes, 0);
}

export function moduleNode(path: string, bytes: number, overrides: Partial<TreemapNodeDto> = {}): TreemapNodeDto {
    return {
        id: `module:${path}`,
        label: path.slice(path.lastIndexOf('/') + 1),
        bytes,
        kind: 'module',
        lazy: false,
        moduleId: path,
        openable: true,
        ...overrides,
    };
}

export function groupNode(id: string, label: string, kind: TreemapKindDto, children: readonly TreemapNodeDto[], overrides: Partial<TreemapNodeDto> = {}): TreemapNodeDto {
    return {
        id,
        label,
        bytes: sum(children),
        kind,
        lazy: children.length > 0 && children.every(child => child.lazy),
        children,
        ...overrides,
    };
}

export function packageNode(name: string, modules: readonly TreemapNodeDto[], overrides: Partial<TreemapNodeDto> = {}): TreemapNodeDto {
    return groupNode(`package:node_modules/${name}`, name, 'package', modules, { packageName: name, duplicate: false, ...overrides });
}

export function rootNode(children: readonly TreemapNodeDto[], label = 'webview'): TreemapNodeDto {
    return groupNode('root', label, 'root', children);
}

export function defaultTreemap(): TreemapNodeDto {
    return rootNode([
        groupNode('group:project', 'Project sources (src/)', 'project', [
            groupNode('dir:src/components', 'components', 'project', [
                moduleNode('src/components/App.vue', 30_000),
                moduleNode('src/components/Lazy.vue', 10_000, { lazy: true }),
            ]),
            moduleNode('src/main.ts', 5_000),
        ]),
        packageNode('vue', [moduleNode('node_modules/vue/dist/vue.runtime.esm-bundler.js', 60_000, { label: 'dist/vue.runtime.esm-bundler.js' })]),
        packageNode('lodash-es', [
            moduleNode('node_modules/lodash-es/debounce.js', 2_000, { label: 'debounce.js' }),
            moduleNode('node_modules/lodash-es/throttle.js', 1_000, { label: 'throttle.js' }),
        ]),
        groupNode('group:generated', 'Generated by the bundler', 'generated', [
            moduleNode('\0vite/preload-helper.js', 1_500, { label: 'vite/preload-helper.js', openable: false }),
        ]),
    ]);
}

export function packageRow(name: string, overrides: Partial<PackageRowDto> = {}): PackageRowDto {
    return { name, versions: ['1.0.0'], bytes: 10_000, lazyBytes: 0, modules: 1, duplicate: false, ...overrides };
}

export function chunkRow(id: string, overrides: Partial<ChunkRowDto> = {}): ChunkRowDto {
    return { id, kind: 'js', bytes: 10_000, loading: 'initial', entry: false, ...overrides };
}

export function assetGroup(kind: AssetGroupDto['kind'], files: readonly (readonly [string, number])[]): AssetGroupDto {
    return {
        kind,
        bytes: files.reduce((total, [, bytes]) => total + bytes, 0),
        files: files.map(([id, bytes]) => ({ id, bytes })),
    };
}

export function budgetState(kind: BudgetKindDto, limit: number, actual: number, label: string = kind): BudgetStateDto {
    return { kind, label, limit, actual, exceeded: actual > limit };
}

export function historyPoint(createdAt: number, total: number, initial = Math.round(total * 0.6)): HistoryPointDto {
    return { createdAt, total, initial, javascript: Math.round(total * 0.75), css: Math.round(total * 0.05) };
}

export function moduleChange(id: string, before: number, after: number): ModuleChangeDto {
    return { id, label: id, before, after, delta: after - before };
}

